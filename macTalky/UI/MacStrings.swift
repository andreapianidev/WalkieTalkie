    var text: String {
        Self.table[Self.languageKey]?[self] ?? Self.en[self] ?? ""
    }

    /// Per le voci con segnaposto printf (%d, %@): l'ordine degli argomenti e'
    /// lo stesso in tutte le lingue, quindi niente segnaposto posizionali.
    func format(_ args: CVarArg...) -> String {
        String(format: text, arguments: args)
    }

    /// Singolare e plurale per i conteggi di dispositivi. Le lingue senza
    /// plurale (giapponese, coreano, cinese, thai, ...) hanno due voci uguali.
    static func count(_ n: Int, one: MacString, many: MacString) -> String {
        (n == 1 ? one : many).format(n)
    }

    /// Lingua scelta da macOS fra quelle della tabella, con le preferenze
    /// dell'utente (anche la lingua impostata solo per Talky). Un portoghese o
    /// un cinese di Hong Kong cadono su "pt" e "zh-Hant", il resto su "en".
    static let languageKey: String =
        Bundle.preferredLocalizations(from: supported).first ?? "en"

    /// Per i maiuscoli: "i".uppercased() senza locale da' "I" anche in turco.
    static var locale: Locale { Locale(identifier: languageKey) }

